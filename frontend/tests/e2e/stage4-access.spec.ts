import { expect, test } from '@playwright/test'
import { openSection, signIn } from './helpers'

test('staff imports a sample PDF and approves it before a bill appears', async ({ page }) => {
  await signIn(page)
  await openSection(page, 'Payments & Bills')
  await page.getByRole('button', { name: 'Utilities', exact: true }).click()
  await page.getByText('Email bill samples and review queue').click()
  await page.getByRole('button', { name: 'Import sample PDF' }).click()
  const form = page.getByRole('form', { name: 'Import utility email sample' })
  await form.getByLabel('Room').selectOption({ label: 'Building 1 · Room 1-A' })
  await form.getByLabel('Utility').selectOption('water')
  await form.getByLabel('Billing month').fill('2030-02')
  await form.getByLabel('Due date').fill('2030-03-10')
  await form.getByLabel('Amount (₱)').fill('187.50')
  await form.getByLabel('Received date').fill('2030-03-01')
  await form.getByLabel('Sender shown in email').fill('sample-provider@example.test')
  await form.getByLabel('Bill PDF').setInputFiles({ name: 'sample.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n%%EOF') })
  await form.getByRole('button', { name: 'Save for review' }).click()
  await expect(page.getByRole('status')).toContainText('No bill has been posted')
  const before = await page.request.get('/api/utility-bills')
  expect((await before.json()).some((bill: { period_month: string }) => bill.period_month === '2030-02')).toBe(false)
  await page.getByRole('button', { name: 'Approve and post bill' }).click()
  await expect(page.getByRole('status')).toContainText('posted as a utility bill')
  const after = await page.request.get('/api/utility-bills')
  expect((await after.json()).some((bill: { period_month: string; amount: string }) => bill.period_month === '2030-02' && bill.amount === '187.50')).toBe(true)
})

test('tenant portal keeps sign-in separate on a phone', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/tenant')
  await expect(page.getByRole('heading', { name: 'Your tenancy' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Tenant sign in' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Staff pages' })).toHaveCount(0)
  const response = await page.request.get('/api/tenant/contracts', { headers: { Accept: 'application/json' } })
  expect(response.status()).toBe(401)
  await page.getByLabel('Email').fill('unknown@example.test')
  await page.getByLabel('Password').fill('incorrect-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('incorrect')
})
