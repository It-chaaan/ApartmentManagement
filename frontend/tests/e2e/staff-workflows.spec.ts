import { expect, test } from '@playwright/test'
import { openSection, ownerEmail, signIn, staffEmail } from './helpers'

test('guest access, sign-in controls, navigation, and sign-out', async ({ page }) => {
  await test.step('Guest cannot read private records', async () => {
    await page.goto('/staff')
    await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
    const response = await page.request.get('/api/tenants', { headers: { Accept: 'application/json' } })
    expect(response.status()).toBe(401)
  })

  await test.step('Invalid credentials show an error and password visibility works', async () => {
    await page.getByLabel('Email address').fill(ownerEmail)
    await page.getByLabel('Password', { exact: true }).fill('incorrect-password')
    await page.getByRole('button', { name: 'Show password' }).click()
    await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text')
    await page.getByRole('button', { name: 'Hide password' }).click()
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('incorrect')
  })

  await test.step('Owner can sign in and reach each management page', async () => {
    await page.getByLabel('Password', { exact: true }).fill(process.env.E2E_TEST_PASSWORD!)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page.getByRole('heading', { level: 1, name: 'Dashboard' })).toBeVisible()
    for (const section of ['Rooms', 'Tenants & contracts', 'Payments & Bills', 'Checklists', 'User Management']) {
      await openSection(page, section)
    }
    await openSection(page, 'Payments & Bills')
    await page.getByText('Download payment reconciliation CSV').click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Download CSV' }).click()
    expect((await downloadPromise).suggestedFilename()).toMatch(/\.csv$/)
  })

  await test.step('Sign-out ends the session', async () => {
    await page.getByRole('button', { name: 'Sign out' }).click()
    await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
    const response = await page.request.get('/api/me', { headers: { Accept: 'application/json' } })
    expect(response.status()).toBe(401)
  })
})

test('phone menu opens management pages and closes after selection', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.getByRole('button', { name: 'Open navigation' })).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('navigation', { name: 'Staff pages' }).getByRole('button', { name: 'Rooms' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Rooms' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open navigation' })).toHaveAttribute('aria-expanded', 'false')
})

test('staff role cannot manage accounts', async ({ page }) => {
  await signIn(page, staffEmail)
  await expect(page.getByRole('navigation', { name: 'Staff pages' }).getByRole('button', { name: 'User Management' })).toHaveCount(0)
  const response = await page.request.get('/api/staff-users', { headers: { Accept: 'application/json' } })
  expect(response.status()).toBe(403)
  await page.goto('/staff#users')
  await expect(page.getByRole('heading', { level: 1, name: 'Dashboard' })).toBeVisible()
})

