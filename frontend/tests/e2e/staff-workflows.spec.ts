test('staff verifies room status through its form and public availability follows', async ({ page }) => {
  await signIn(page)
  await openSection(page, 'Rooms')
  await page.getByRole('searchbox', { name: 'Search rooms' }).fill('1-A')
  await expect(page.getByText('1 of 18 rooms')).toBeVisible()
  await page.getByRole('button', { name: 'View details for Building 1 Room 1-A' }).click()
  const dialog = page.getByRole('dialog', { name: 'Room 1-A details' })
  await dialog.getByLabel('Status').selectOption('available')
  await dialog.getByRole('button', { name: 'Save changes' }).click()
  await expect(dialog.getByRole('status')).toContainText('Room details saved.')
  const publicResponse = await page.request.get('/api/public/site')
  expect(publicResponse.ok()).toBeTruthy()
  const site = await publicResponse.json()
  const room = site.buildings[0].rooms.find((item: { code: string }) => item.code === '1-A')
  expect(room.availability).toBe('available')
})

test('tenant, contract, signing, move-in, and rent correction workflow', async ({ page }) => {
  await signIn(page)
  await test.step('Verify a room before signing', async () => {
    await openSection(page, 'Rooms')
    await page.getByRole('searchbox', { name: 'Search rooms' }).fill('1-C')
    await page.getByRole('button', { name: 'View details for Building 1 Room 1-C' }).click()
    const dialog = page.getByRole('dialog', { name: 'Room 1-C details' })
    await dialog.getByLabel('Status').selectOption('available')
    await dialog.getByRole('button', { name: 'Save changes' }).click()
    await expect(dialog.getByRole('status')).toContainText('Room details saved.')
    await dialog.getByRole('button', { name: 'Close details' }).click()
  })

  await test.step('Add a tenant and contract draft', async () => {
    await openSection(page, 'Tenants & contracts')
    await page.getByRole('button', { name: 'Add tenant' }).click()
    const tenantForm = page.getByRole('form', { name: 'Tenant profile' })
    await tenantForm.getByLabel('Full name').fill('E2E Tenant')
    await tenantForm.getByLabel('Phone', { exact: true }).fill('09170000001')
    await tenantForm.getByRole('button', { name: 'Save profile' }).click()
    await expect(page.getByRole('status')).toContainText('Tenant profile saved.')
    await page.getByRole('button', { name: 'Create contract' }).click()
    const draft = page.getByRole('form', { name: 'Contract draft' })
    await draft.getByRole('combobox', { name: 'Room', exact: true }).selectOption({ label: 'Building 1 · Room 1-C (available)' })
    await draft.getByRole('button', { name: 'Save draft' }).click()
    await expect(page.getByRole('status')).toContainText('Contract draft saved.')
    await expect(page.getByRole('heading', { name: /Room 1-C.*E2E Tenant/ })).toBeVisible()
  })

  await test.step('Record signing payment and start tenancy', async () => {
    await page.getByRole('checkbox', { name: 'I confirm the full signing payment was received.' }).check()
    await page.getByRole('button', { name: 'Confirm signing and payments' }).click()
    await expect(page.getByRole('button', { name: 'Start tenancy' })).toBeVisible()
    await page.getByRole('button', { name: 'Start tenancy' }).click()
    await expect(page.getByText(/Contract #\d+ · active/)).toBeVisible()
  })

  await test.step('Record later rent then correct it without erasing history', async () => {
    await page.getByRole('button', { name: 'View payments' }).click()
    const rentForm = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Record payment' }) })
    const next = new Date()
    next.setMonth(next.getMonth() + 1)
    await rentForm.getByLabel('Rent month').selectOption(next.toLocaleDateString('en-CA').slice(0, 7))
    await rentForm.getByLabel('Amount (₱)').fill('5000')
    await rentForm.getByRole('button', { name: 'Record payment' }).click()
    await expect(page.getByRole('status')).toContainText('Payment recorded.')
    const correction = page.getByRole('region', { name: 'Rent payment corrections' })
    await correction.getByRole('button', { name: 'Correct entry' }).click()
    await correction.getByLabel(/Reason for voiding payment/).fill('Duplicate test payment')
    await correction.getByRole('button', { name: 'Void payment' }).click()
    await expect(correction.getByText('Voided by E2E Owner: Duplicate test payment')).toBeVisible()
  })
})

test('utility payment correction and room checklist workflow', async ({ page }) => {
  await signIn(page)
  await test.step('Add a utility bill and partially pay it', async () => {
    await openSection(page, 'Payments & Bills')
    await page.getByRole('button', { name: 'Utilities' }).click()
    const bills = page.getByRole('region', { name: 'Utility bills' })
    await bills.getByRole('button', { name: 'Add bill' }).click()
    const form = page.getByRole('form', { name: 'New utility bill' })
    await form.getByRole('combobox', { name: 'Room', exact: true }).selectOption({ label: 'Building 1 · Room 1-D' })
    await form.getByLabel('Due date').fill(new Date().toLocaleDateString('en-CA'))
    await form.getByLabel('Amount (₱)').fill('900')
    await form.getByRole('button', { name: 'Save bill' }).click()
    await expect(bills.getByRole('status')).toContainText('Bill recorded.')
    const payment = bills.getByRole('heading', { name: 'Record payment' }).locator('..')
    await payment.getByLabel('Amount (₱)').fill('400')
    await payment.getByRole('button', { name: 'Save payment' }).click()
    await expect(bills.getByRole('status')).toContainText('Payment recorded.')
    await bills.getByRole('button', { name: 'Correct entry' }).click()
    await bills.getByLabel(/Reason for voiding payment/).fill('Wrong account payment')
    await bills.getByRole('button', { name: 'Void payment' }).click()
    await expect(bills.getByText('Voided by E2E Owner: Wrong account payment')).toBeVisible()
  })

  await test.step('Save and find a room inspection', async () => {
    await openSection(page, 'Checklists')
    const checklists = page.getByRole('region', { name: 'Unit checklists' })
    await checklists.getByRole('combobox', { name: 'Room', exact: true }).selectOption({ label: 'Building 1 · Room 1-D · Unverified' })
    await checklists.getByLabel('General notes').fill('E2E routine inspection')
    await checklists.getByRole('button', { name: 'Save checklist' }).click()
    await expect(page.getByRole('status')).toContainText('Inspection checklist saved.')
    await checklists.getByRole('button', { name: 'History' }).click()
    await expect(checklists.getByText('E2E routine inspection')).toBeVisible()
  })
})
